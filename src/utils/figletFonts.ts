// Generic Renderer function given a dictionary
function renderFromDict(text: string, dict: Record<string, string[]>, height: number, letterSpacing: number = 0): string {
  const lines: string[] = Array(height).fill('');
  const spacingStr = ' '.repeat(Math.max(0, letterSpacing));

  for (let i = 0; i < text.length; i++) {
    const rawChar = text[i];
    const char = rawChar.toLowerCase();
    
    let glyph = dict[char];
    if (!glyph) {
      glyph = dict[rawChar];
    }

    if (!glyph) {
      // Fallback: render basic block character
      glyph = Array(height).fill(rawChar);
    }

    for (let row = 0; row < height; row++) {
      const rowContent = glyph[row] || ' '.repeat(glyph[0]?.length || 3);
      lines[row] += (i > 0 ? spacingStr : '') + rowContent;
    }
  }

  return lines.join('\n');
}

